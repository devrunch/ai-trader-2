// Regenerates the client from the compute service's OpenAPI document (SRD §10.2).
// `--check` generates into a temporary folder and fails if the committed files differ.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createClient } from '@hey-api/openapi-ts';

const pkg = path.resolve(import.meta.dirname, '..');
const service = path.resolve(pkg, '../../services/compute');
const GENERATED = ['openapi.json', 'src/generated/types.gen.ts', 'src/generated/zod.gen.ts'];
const HEADER = '// Generated by packages/compute-client/scripts/generate.ts. Do not edit.';

async function generate(into: string): Promise<void> {
  const spec = path.join(into, 'openapi.json');
  execFileSync('uv', ['run', '--frozen', '--project', service, 'python', '-m', 'compute.openapi', spec], { stdio: 'inherit' });
  await createClient({
    input: spec,
    output: {
      path: path.join(into, 'src/generated'), header: HEADER, entryFile: false,
      tsConfigPath: path.join(pkg, 'tsconfig.json'), module: { extension: '.js' },
    },
    plugins: ['@hey-api/typescript', { name: 'zod', compatibilityVersion: 4 }],
    logs: { level: 'warn' },
  });
  // Recursive schemas come out as `z.lazy((): any => …)`; type them as ZodType so no `any` leaks.
  const zod = path.join(into, 'src/generated/zod.gen.ts');
  writeFileSync(zod, readFileSync(zod, 'utf8').replaceAll('(): any =>', '(): z.ZodType =>'));
}

function read(file: string): string | undefined {
  return existsSync(file) ? readFileSync(file, 'utf8') : undefined;
}

async function check(): Promise<void> {
  const temp = mkdtempSync(path.join(tmpdir(), 'compute-client-'));
  try {
    await generate(temp);
    const produced = readdirSync(path.join(temp, 'src/generated')).map(f => `src/generated/${f}`);
    const stale = [...new Set([...GENERATED, ...produced, 'openapi.json'])]
      .filter(file => read(path.join(temp, file)) !== read(path.join(pkg, file)));
    if (stale.length > 0) {
      console.error(`compute-client is out of date (${stale.join(', ')}). Run: pnpm generate:compute-client`);
      process.exitCode = 1;
    }
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
}

if (process.argv.includes('--check')) await check();
else await generate(pkg);
