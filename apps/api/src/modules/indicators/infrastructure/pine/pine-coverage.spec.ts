import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import type { IndicatorComputeRequest, PineCoverageRow } from '@aitrader/contracts';
import { fixtureBars } from '../native/bars.spec-helper';
import { pineHarness, type PineHarness } from './pine.spec-helper';
import { PROBES, type CompletionKind, type Probe } from './pine-coverage-probes.spec-helper';

// FR-IN-26, FR-IN-27: the coverage report is what the runtime does with each probe, written to packages/contracts.
const TARGET = join(__dirname, '..', '..', '..', '..', '..', '..', '..', 'packages', 'contracts', 'src', 'pine-coverage.ts');
const HEADER = "//@version=5\nindicator(\"probe\", overlay=true)\n";
const bars = fixtureBars(60, 5);

interface Outcome { probe: Probe; status: 'supported' | 'refused'; note: string }
interface Completion { label: string; kind: CompletionKind; detail: string }

const sourceOf = (probe: Probe): string => probe.source ?? `${HEADER}${probe.body}\nplot(close)`;
const request = (source: string): IndicatorComputeRequest => ({ symbol: 'NSE:X', interval: '15', indicator: { kind: 'pine', source, inputs: {} }, range: { limit: 20 } });

/** The runtime's own refusal text, without the line number (it depends on the probe template). */
function refusal(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error);
  return message.replace(/ at line \d+/, '').replace(/ \(line \d+\)/, '').replace(/\s+/g, ' ').trim().slice(0, 160);
}

async function run(harness: PineHarness, source: string): Promise<{ status: 'supported' | 'refused'; note: string }> {
  try {
    await harness.service.compute(request(source));
    return { status: 'supported', note: '' };
  } catch (error) {
    return { status: 'refused', note: refusal(error) };
  }
}

/** A string literal the way eslint wants it: single quotes, double when the text holds a single quote. */
const q = (text: string): string => {
  const escaped = text.replace(/\\/g, '\\\\');
  return escaped.includes("'") && !escaped.includes('"') ? `"${escaped}"` : `'${escaped.replace(/'/g, "\\'")}'`;
};
const byText = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

function completionsOf(outcomes: readonly Outcome[]): Completion[] {
  const found = new Map<string, Completion>();
  for (const { probe, status } of outcomes) {
    if (status !== 'supported') continue;
    for (const label of probe.names) if (!found.has(label)) found.set(label, { label, kind: probe.kind, detail: probe.detail });
  }
  for (const label of [...found.keys()]) {
    const space = label.split('.')[0] ?? label;
    if (label.includes('.') && !found.has(space)) found.set(space, { label: space, kind: 'keyword', detail: 'namespace' });
  }
  return [...found.values()].sort((a, b) => byText(a.label, b.label));
}

function generate(outcomes: readonly Outcome[]): string {
  const rows: PineCoverageRow[] = outcomes
    .map(({ probe, status, note }) => ({ group: probe.group, feature: probe.feature, status, note }))
    .sort((a, b) => byText(a.group, b.group) || byText(a.feature, b.feature));
  const row = (r: PineCoverageRow): string => `  { group: ${q(r.group)}, feature: ${q(r.feature)}, status: ${q(r.status)}, note: ${q(r.note)} },`;
  const completion = (c: Completion): string => `  { label: ${q(c.label)}, kind: ${q(c.kind)}, detail: ${q(c.detail)} },`;
  return [
    "import type { PineCoverageRow } from './pine-script.js';",
    '',
    '/** Generated by `pine-coverage.spec.ts` in the API (run with UPDATE_PINE_COVERAGE=1 to rewrite); never edited by hand. */',
    'export const PINE_COVERAGE: readonly PineCoverageRow[] = [',
    ...rows.map(row),
    '];',
    '',
    '/** Names the editor offers while typing, generated with the coverage table; every one runs in the runtime. */',
    "export const PINE_COMPLETIONS: readonly { label: string; kind: 'function' | 'variable' | 'constant' | 'keyword'; detail: string }[] = [",
    ...completionsOf(outcomes).map(completion),
    '];',
    '',
  ].join('\n');
}

let harness: PineHarness | undefined;
let outcomes: Promise<Outcome[]> | undefined;
afterAll(() => { harness?.pool.close(); });

/** Runs every probe once for the whole file, a few at a time on the shared pool. */
function probeAll(): Promise<Outcome[]> {
  outcomes ??= (async () => {
    harness = await pineHarness(bars, {}, { timeoutMs: 30_000 });
    const results: Outcome[] = [];
    for (let i = 0; i < PROBES.length; i += 8) {
      const chunk = PROBES.slice(i, i + 8);
      const done = await Promise.all(chunk.map(async probe => ({ probe, ...(await run(harness as PineHarness, sourceOf(probe))) })));
      results.push(...done);
    }
    return results;
  })();
  return outcomes;
}

describe('Pine coverage report', () => {
  it('refuses a function PineTS does not have, so a pass is not "anything runs"', async () => {
    await probeAll();
    const bogus = await run(harness as PineHarness, `${HEADER}x = ta.bogus(close, 3)\nplot(close)`);
    expect(bogus.status).toBe('refused');
    expect(bogus.note).toContain('ta.bogus');
  }, 120_000);

  it('runs each probe through the real runtime and gets the outcome the table expects', async () => {
    const results = await probeAll();
    const mismatches = results.filter(({ probe, status }) => status !== probe.expect).map(({ probe, status, note }) => `${probe.feature}: expected ${probe.expect}, got ${status} ${note}`);
    expect(mismatches).toEqual([]);
  }, 120_000);

  it('has one row per feature', async () => {
    const features = (await probeAll()).map(({ probe }) => `${probe.group}/${probe.feature}`);
    expect(features.filter((f, i) => features.indexOf(f) !== i)).toEqual([]);
  }, 120_000);

  it('matches packages/contracts/src/pine-coverage.ts (UPDATE_PINE_COVERAGE=1 rewrites it)', async () => {
    const text = generate(await probeAll());
    // A developer switch for regenerating the file, not app config.
    // eslint-disable-next-line no-restricted-properties
    if (process.env['UPDATE_PINE_COVERAGE'] === '1') writeFileSync(TARGET, text);
    expect(readFileSync(TARGET, 'utf8')).toBe(text);
  }, 120_000);
});
