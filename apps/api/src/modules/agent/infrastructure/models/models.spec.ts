import { describe, expect, it } from 'vitest';
import { bedrockMantleKey } from './bedrock-mantle-key';
import { createLanguageModel, parseModelSpec, type ModelEnv } from './model-factory';

const env: ModelEnv = {
  ANTHROPIC_API_KEY: 'sk-ant-test', OPENAI_API_KEY: 'sk-test', XAI_API_KEY: 'xai-test', GOOGLE_GENERATIVE_AI_API_KEY: 'g-test',
  AGENT_BASE_URL: 'https://openrouter.ai/api/v1', AGENT_API_KEY: 'or-test',
  AWS_REGION: 'ap-south-1', BEDROCK_API_KEY: 'bedrock-api-key-test',
};

describe('parseModelSpec (provider and model are configuration, not code)', () => {
  it('splits provider/model; model ids may contain slashes and colons', () => {
    expect(parseModelSpec('bedrock-mantle/deepseek.v3.2')).toEqual({ provider: 'bedrock-mantle', modelId: 'deepseek.v3.2' });
    expect(parseModelSpec('openai-compatible/meta-llama/llama-3.3-70b:free')).toEqual({ provider: 'openai-compatible', modelId: 'meta-llama/llama-3.3-70b:free' });
  });
  it('rejects unknown providers and missing model ids with the list of supported providers', () => {
    expect(() => parseModelSpec('mystery/x')).toThrow(/bedrock-mantle, anthropic, google, xai, openai, openai-compatible/);
    expect(() => parseModelSpec('anthropic/')).toThrow(/model id/);
  });
});

describe('createLanguageModel', () => {
  it.each([
    ['anthropic/claude-sonnet-4-5', 'claude-sonnet-4-5'],
    ['xai/grok-4', 'grok-4'],
    ['google/gemini-2.5-pro', 'gemini-2.5-pro'],
    ['openai/gpt-5', 'gpt-5'],
    ['openai-compatible/meta-llama/llama-3.3-70b', 'meta-llama/llama-3.3-70b'],
    ['bedrock-mantle/deepseek.v3.2', 'deepseek.v3.2'],
  ])('%s builds a model', (spec, modelId) => {
    expect(createLanguageModel(parseModelSpec(spec), env).modelId).toBe(modelId);
  });

  it('a missing key names the exact .env variable', () => {
    expect(() => createLanguageModel(parseModelSpec('anthropic/claude'), {})).toThrow('ANTHROPIC_API_KEY');
    expect(() => createLanguageModel(parseModelSpec('xai/grok-4'), {})).toThrow('XAI_API_KEY');
    expect(() => createLanguageModel(parseModelSpec('google/gemini-2.5-pro'), {})).toThrow('GOOGLE_GENERATIVE_AI_API_KEY');
    expect(() => createLanguageModel(parseModelSpec('openai-compatible/x'), { AGENT_API_KEY: 'k' })).toThrow('AGENT_BASE_URL');
    expect(() => createLanguageModel(parseModelSpec('bedrock-mantle/deepseek.v3.2'), { AWS_REGION: 'ap-south-1' })).toThrow(/BEDROCK_API_KEY or AWS_ACCESS_KEY_ID/);
  });
});

describe('bedrockMantleKey (ported from the old repo)', () => {
  const key = bedrockMantleKey({ accessKeyId: 'AKIDEXAMPLE', secretAccessKey: 'wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY', region: 'ap-south-1' },
    { expiresIn: 43_200, signingDate: new Date('2026-11-10T06:00:00Z') });

  it('is a presigned CallWithBearerToken URL, base64-encoded, with Version appended after signing', async () => {
    const value = await key;
    expect(value.startsWith('bedrock-api-key-')).toBe(true);
    const url = Buffer.from(value.slice('bedrock-api-key-'.length), 'base64').toString('utf8');
    expect(url.startsWith('bedrock.amazonaws.com/?')).toBe(true);
    expect(url).toContain('Action=CallWithBearerToken');
    expect(url).toContain('X-Amz-Algorithm=AWS4-HMAC-SHA256');
    expect(url).toContain('X-Amz-Credential=AKIDEXAMPLE%2F20261110%2Fap-south-1%2Fbedrock%2Faws4_request');
    expect(url).toContain('X-Amz-Expires=43200');
    expect(url).toMatch(/X-Amz-Signature=[0-9a-f]{64}/);
    expect(url.endsWith('&Version=1')).toBe(true);
  });

  it('is deterministic for the same credentials and time', async () => {
    const again = await bedrockMantleKey({ accessKeyId: 'AKIDEXAMPLE', secretAccessKey: 'wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY', region: 'ap-south-1' },
      { expiresIn: 43_200, signingDate: new Date('2026-11-10T06:00:00Z') });
    expect(again).toBe(await key);
  });

  it('matches the old repo Python (botocore) key byte for byte', async () => {
    // Generated by ai-trader-signals' botocore SigV4QueryAuth with these example credentials at 2026-11-10T08:31:58Z.
    const python = 'bedrock.amazonaws.com/?Action=CallWithBearerToken&X-Amz-Algorithm=AWS4-HMAC-SHA256&X-Amz-Credential=AKIDEXAMPLE%2F20261110%2Fap-south-1%2Fbedrock%2Faws4_request&X-Amz-Date=20261110T083158Z&X-Amz-Expires=43200&X-Amz-SignedHeaders=host&X-Amz-Signature=138c465bdcc7185846264db6395c520b881e5cf757b748c0f3cba0b8df879d2f&Version=1';
    const ours = await bedrockMantleKey({ accessKeyId: 'AKIDEXAMPLE', secretAccessKey: 'wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY', region: 'ap-south-1' },
      { expiresIn: 43_200, signingDate: new Date('2026-11-10T08:31:58Z') });
    expect(ours).toBe(`bedrock-api-key-${Buffer.from(python, 'utf8').toString('base64')}`);
  });
});
